  function quiz() {
    const box = $('#quiz'), nEl = $('#qzN');
    if (nEl) nEl.textContent = QUIZ.length;
    let order, i, score, answered;
    const shuffle = a => { a = a.slice(); for (let k = a.length - 1; k > 0; k--) { const j = Math.floor(Math.random() * (k + 1)); [a[k], a[j]] = [a[j], a[k]]; } return a; };
    function start() { order = shuffle(QUIZ.map((_, k) => k)); i = 0; score = 0; show(); }
    function show() {
      if (i >= order.length) return end();
      answered = false;
      const [q, opts, exp] = QUIZ[order[i]];
      const sh = shuffle(opts.map((t, k) => ({ t, ok: k === 0 })));
      box.innerHTML = `<div class="qz-card"><div class="qz-top"><span>السؤال ${i + 1} من ${order.length}</span><span>النتيجة: ${score}</span></div><div class="qz-bar"><i style="width:${(i / order.length) * 100}%"></i></div><div class="qz-q">${q}</div><div class="qz-opts">${sh.map((o, k) => `<button type="button" data-k="${k}">${o.t}</button>`).join('')}</div><div class="qz-exp" hidden></div><div class="ctrls" hidden><button class="btn primary" type="button" data-next>${i + 1 < order.length ? 'السؤال التالي' : 'النتيجة'}</button></div></div>`;
      const btns = L.$$('.qz-opts button', box), ex = $('.qz-exp', box), nx = $('[data-next]', box);
      btns.forEach(b => b.addEventListener('click', () => {
        if (answered) return; answered = true;
        const o = sh[+b.dataset.k];
        if (o.ok) score++;
        btns.forEach((x, k) => { x.disabled = true; if (sh[k].ok) x.classList.add('right'); });
        if (!o.ok) b.classList.add('wrong');
        ex.innerHTML = (o.ok ? '<b style="color:var(--accent)">صحيح.</b> ' : '<b style="color:var(--pen)">ليس هذا.</b> ') + exp;
        ex.hidden = false; nx.parentNode.hidden = false; nx.focus({ preventScroll: true });
        $('.qz-top span:last-child', box).textContent = 'النتيجة: ' + score;
      }));
      nx.addEventListener('click', () => { i++; show(); });
    }
    function end() {
      const pct = Math.round((score / order.length) * 100);
      const word = pct >= 90 ? 'ممتاز، أنت جاهز للامتحان.' : pct >= 70 ? 'جيد جداً. راجع الأسئلة التي أخطأت فيها.' : pct >= 50 ? 'مقبول. ارجع إلى الأقسام وجرّب المحاكاة مرة ثانية.' : 'تحتاج مراجعة. ابدأ ببطاقات «علل» والأرقام ثم أعد الاختبار.';
      box.innerHTML = `<div class="qz-card"><div class="qz-bar"><i style="width:100%"></i></div><div class="qz-q">نتيجتك: <span style="font-family:var(--f-mono)">${score} / ${order.length}</span> (${pct}%)</div><p style="color:var(--ink-2)">${word}</p><div class="ctrls"><button class="btn primary" type="button" data-again>أعد الاختبار</button></div></div>`;
      $('[data-again]', box).addEventListener('click', start);
    }
    start();
  }

